#!/bin/bash

# 🤖 Скрипт запуска оптимизированной системы агентов
# Автор: Система агентов
# Дата: $(date)

echo "🚀 Запуск оптимизированной системы агентов (6 агентов)"
echo "====================================================="
echo ""

# Проверка наличия файлов агентов
echo "📋 Проверка файлов агентов..."
agents=(
    "architect_agent.md:🏗️ Архитектор-агент (Координатор)"
    "backend_agent.md:⚙️ Бэкенд-агент (Серверная логика)"
    "frontend_agent.md:🎨 Фронтенд-агент (Пользовательский интерфейс)"
    "testing_agent.md:🧪 Агент-тестировщик (Качество и отладка)"
    "devops_agent.md:🔧 Агент-DevOps (Инфраструктура и автоматизация)"
    "analyst_agent.md:📊 Агент-аналитик (Данные и отчеты)"
)

for agent in "${agents[@]}"; do
    file="${agent%%:*}"
    name="${agent##*:}"
    if [ -f "$file" ]; then
        echo "✅ $name готов к работе"
    else
        echo "❌ Файл $file не найден"
    fi
done

echo ""
echo "🎯 Готовые команды для работы с оптимизированными агентами:"
echo ""

echo "🏗️ АРХИТЕКТОР-АГЕНТ (Координатор):"
echo "   Архитектор-агент, координируй работу агентов"
echo "   Архитектор-агент, планируй спринт"
echo "   Архитектор-агент, контролируй прогресс"
echo ""

echo "⚙️ БЭКЕНД-АГЕНТ (Серверная логика):"
echo "   Бэкенд-агент, оптимизируй производительность API"
echo "   Бэкенд-агент, улучши безопасность"
echo "   Бэкенд-агент, интегрируй с системой мониторинга"
echo ""

echo "🎨 ФРОНТЕНД-АГЕНТ (Пользовательский интерфейс):"
echo "   Фронтенд-агент, улучши адаптивность интерфейса"
echo "   Фронтенд-агент, добавь accessibility функции"
echo "   Фронтенд-агент, оптимизируй производительность компонентов"
echo ""

echo "🧪 АГЕНТ-ТЕСТИРОВЩИК (Качество и отладка):"
echo "   Агент-тестировщик, создай автоматизированные тесты"
echo "   Агент-тестировщик, интегрируй с CI/CD пайплайном"
echo "   Агент-тестировщик, проведи нагрузочное тестирование"
echo ""

echo "🔧 АГЕНТ-DEVOPS (Инфраструктура и автоматизация):"
echo "   Агент-DevOps, настрой CI/CD пайплайн"
echo "   Агент-DevOps, автоматизируй деплой"
echo "   Агент-DevOps, настрой мониторинг"
echo ""

echo "📊 АГЕНТ-АНАЛИТИК (Данные и отчеты):"
echo "   Агент-аналитик, проанализируй экономическую модель"
echo "   Агент-аналитик, создай отчет о производительности"
echo "   Агент-аналитик, валидируй корректность расчетов"
echo ""

echo "📚 ДОПОЛНИТЕЛЬНЫЕ КОМАНДЫ:"
echo "   - Прочитать рекомендации: cat AGENT_OPTIMIZATION_SUMMARY.md"
echo "   - Просмотреть план миграции: cat AGENT_OPTIMIZATION_RECOMMENDATIONS.md"
echo "   - Запустить быструю проверку: ../scripts/quick_check.sh"
echo ""

echo "🚀 ОПТИМИЗИРОВАННАЯ СИСТЕМА ГОТОВА К РАБОТЕ!"
echo "Начните с команды: Архитектор-агент, координируй работу агентов"
echo ""

# Создание структуры папок если её нет
if [ ! -d "scripts" ]; then
    echo "📁 Создание папки scripts..."
    mkdir -p scripts
fi

if [ ! -d "analysis" ]; then
    echo "📁 Создание папки analysis..."
    mkdir -p analysis
fi

if [ ! -d "reports" ]; then
    echo "📁 Создание папки reports..."
    mkdir -p reports
fi

echo ""
echo "📊 Статистика оптимизации:"
echo "   Было агентов: 4"
echo "   Стало агентов: 6"
echo "   Новые агенты: DevOps, Аналитик"
echo "   Улучшения: Специализация, Автоматизация, Эффективность"
echo ""

echo "🎯 Следующие шаги:"
echo "   1. Архитектор-агент координирует работу"
echo "   2. Агент-DevOps настраивает автоматизацию"
echo "   3. Агент-аналитик создает систему отчетности"
echo "   4. Все агенты работают параллельно"
echo "" 